# Operadores de Atribuição

x = 5      # Atribuição simples
print(f"x = {x}")

x += 3     # x = x + 3
print(f"x += 3 -> {x}")

x = 5      # reset
x -= 3     # x = x - 3
print(f"x -= 3 -> {x}")

x = 5
x *= 3     # x = x * 3
print(f"x *= 3 -> {x}")

x = 5
x /= 3     # x = x / 3
print(f"x /= 3 -> {x}")

x = 5
x %= 3     # x = x % 3
print(f"x %= 3 -> {x}")

x = 5
x //= 3    # x = x // 3
print(f"x //= 3 -> {x}")

x = 5
x **= 3    # x = x ** 3
print(f"x **= 3 -> {x}")
