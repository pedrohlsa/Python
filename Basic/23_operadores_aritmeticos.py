# Operadores Aritméticos

x = 15
y = 4

print(x + y)   # Soma: 19
print(x - y)   # Subtração: 11
print(x * y)   # Multiplicação: 60
print(x / y)   # Divisão: 3.75
print(x % y)   # Módulo (resto): 3
print(x ** y)  # Exponenciação: 15⁴ = 50625
print(x // y)  # Floor division (parte inteira): 3

# Exemplos extras
